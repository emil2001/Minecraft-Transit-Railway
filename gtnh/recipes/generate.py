#!/usr/bin/env python3
"""Generate the self-contained GTNH recipe script without starting Minecraft."""

import argparse
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]


def original_recipes():
    recipes = {}
    for path in sorted((REPO / "fabric/src/main/resources/data").glob("*/recipes/*.json")):
        recipes[path.parents[1].name + ":" + path.stem] = json.loads(path.read_text())
    if len(recipes) != 308:
        raise ValueError("Expected the pinned 308 original recipes")
    return recipes


def stack(identifier, metadata=None, amount=1):
    result = "<" + identifier + (":" + str(metadata) if metadata is not None else "") + ">"
    return result if amount == 1 else result + ".withAmount(" + str(amount) + ")"


def original_ingredient(ingredient):
    identifier = ingredient.get("item", "")
    # Every reviewed restoration is a conversion between MTR items. Fail closed
    # if future edits need modern vanilla aliases or legacy tag alternatives.
    if set(ingredient) != {"item"} or not identifier.startswith(("mtr:", "mtrsteamloco:")):
        raise ValueError("Restoration requires an explicit MTR item: " + str(ingredient))
    return stack(identifier)


def replacement_ingredient(ingredient, machine=False):
    amount = ingredient["amount"] if machine else 1
    if ingredient["kind"] == "item":
        return stack(ingredient["id"], ingredient.get("meta"), amount)
    result = "<ore:" + ingredient["id"] + ">"
    if ingredient.get("canonical", False):
        return result + ".firstItem.withAmount(" + str(amount) + ")"
    return result if amount == 1 else result + " * " + str(amount)


def restored_recipe(identifier, recipe):
    output = stack(recipe["result"]["item"], amount=recipe["result"].get("count", 1))
    if recipe["type"] != "minecraft:crafting_shapeless":
        raise ValueError("Restoration must be a reviewed shapeless conversion: " + identifier)
    inputs = ", ".join(original_ingredient(value) for value in recipe["ingredients"])
    return "recipes.addShapeless(" + output + ", [" + inputs + "]);"


def replacement_recipe(recipe):
    output = stack(recipe["output"], amount=recipe["count"])
    if recipe["method"] == "assembler":
        if len(recipe["inputs"]) > 6:
            raise ValueError("Assembler has more than six inputs: " + recipe["output"])
        if not recipe.get("fluid"):
            raise ValueError("Array assembler recipes need explicit fluid: " + recipe["output"])
        inputs = ", ".join(replacement_ingredient(value, True) for value in recipe["inputs"])
        fluid = "<liquid:" + recipe["fluid"]["id"] + "> * " + str(recipe["fluid"]["amount"])
        return ("Assembler.addRecipe(" + output + ", [" + inputs + "], " + fluid + ", "
                + str(recipe["duration"]) + ", " + str(recipe["eut"]) + ");")
    if recipe["method"] != "shapeless":
        raise ValueError("Replacement crafting recipes must be shapeless: " + recipe["output"])
    # Crafting consumes one item per occupied slot. Repeat ingredients instead of
    # relying on a multi-item IIngredient amount in one crafting slot.
    inputs = [replacement_ingredient(value) for value in recipe["inputs"] for _ in range(value["amount"])]
    if not 1 <= len(inputs) <= 9:
        raise ValueError("Crafting recipe does not fit the grid: " + recipe["output"])
    return "recipes.addShapeless(" + output + ", [" + ", ".join(inputs) + "]);"


def generate(profile_path=None, output_path=None):
    profile = json.loads(Path(profile_path or HERE / "profile.json").read_text())
    if profile["schema"] != 1:
        raise ValueError("Unsupported recipe profile schema")
    originals = original_recipes()
    replacements = sorted(profile["replacements"], key=lambda value: value["output"])
    targets = {value["output"] for value in replacements}
    if len(targets) != len(replacements):
        raise ValueError("Duplicate replacement output")
    if len(set(profile["restore"])) != len(profile["restore"]):
        raise ValueError("Duplicate restored recipe")
    lines = ["// MTR 4.0.5-gtnh.2 / GT New Horizons 2.9.0-RC-2 recipe integration.",
             "// Generated by gtnh/recipes/generate.py; edit profile.json, then regenerate.",
             "// Requires CraftTweaker 3.4.8, GTTweaker 2.3.4 and GregTech 5.09.54.205.",
             "// Restart the client after adding, changing or removing this script.",
             "", "import mods.gregtech.Assembler;", "", "// Remove every original recipe for each changed output."]
    lines.extend("recipes.remove(" + stack(identifier) + ");" for identifier in sorted(targets))
    lines.extend(["", "// Restore only the reviewed original conversions."])
    for identifier in sorted(profile["restore"]):
        recipe = originals[identifier]
        if recipe["result"]["item"] not in targets:
            raise ValueError("Restored recipe output was not removed: " + identifier)
        if identifier.startswith("mtr:tunnel_creator_"):
            raise ValueError("Original tunnel-tool conversions multiply tools: " + identifier)
        lines.extend(["// " + identifier, restored_recipe(identifier, recipe)])
    lines.extend(["", "// Controlled base recipes. Circuits accept every registered equivalent at their tier."])
    for recipe in replacements:
        lines.extend(["// " + recipe["tier"] + ": " + recipe["output"], replacement_recipe(recipe)])
    text = "\n".join(lines) + "\n"
    if output_path is not None:
        Path(output_path).write_text(text)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", type=Path, default=HERE / "profile.json")
    parser.add_argument("--output", type=Path, default=HERE / "MTR-GTNH.zs")
    parser.add_argument("--check", action="store_true", help="Fail if the committed script differs from generation")
    args = parser.parse_args()
    text = generate(args.profile)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != text:
            parser.exit(1, "Recipe script is out of date; run generate.py\n")
        print("Recipe script matches profile and original resources")
    else:
        args.output.write_text(text)
        print("Wrote " + str(args.output))


if __name__ == "__main__":
    main()
